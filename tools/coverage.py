#!/usr/bin/env python3
"""Diagnosis coverage — how much of a reference failure catalog the structured diagnosis covers.

Rows: tests/veracity/coverage.yaml (one per cause). Every column but ``live`` is checked
against the code, not declared:

- signals  every kind the row needs is in ``rca.signals.SIGNAL_KINDS``
- rule     the row's rule is in ``rca.diagnosis.RULE_IDS``
- case     at least one of the row's cases PASSes in the latest ``structured`` replay
- covered  signals + rule + case

``--runbooks DIR`` also checks each row's ``terms`` against the text of the runbooks it
cites (prometheus-operator/runbooks @ a685d14cf512, kept outside the repo).

Usage::

    python tools/coverage.py                       # writes docs/diagnosis-coverage.md
    python tools/coverage.py --runbooks /path/to/runbooks
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

ROWS = ROOT / "tests/veracity/coverage.yaml"
RUNBOOK_NAMES = ROOT / "tests/veracity/runbooks-a685d14.txt"
BASELINES = ROOT / "tests/veracity/replay-baselines"
REPORT = ROOT / "docs/diagnosis-coverage.md"


def load_rows() -> list[dict]:
    return yaml.safe_load(ROWS.read_text())["rows"]


def runbook_names() -> list[str]:
    return [line.strip() for line in RUNBOOK_NAMES.read_text().splitlines()
            if line.strip() and not line.startswith("#")]


def latest_structured() -> Path | None:
    dirs = sorted(BASELINES.glob("structured-*"))
    return dirs[-1] if dirs else None


def passing_cases(run_dir: Path | None) -> set[str]:
    if run_dir is None:
        return set()
    passed = set()
    for f in run_dir.glob("structured/*/run_1.json"):
        record = json.loads(f.read_text())
        if record.get("veracity") == "PASS":
            passed.add(record["case"].split("_", 1)[0])
    return passed


def evaluate(rows: list[dict], passed: set[str]) -> list[dict]:
    from rca.diagnosis import RULE_IDS
    from rca.signals import SIGNAL_KINDS

    out = []
    for r in rows:
        unknown = [k for k in r.get("signals", []) if k not in SIGNAL_KINDS]
        signals_ok = bool(r.get("signals")) and not unknown
        rule_ok = r.get("rule") in RULE_IDS
        negative = r.get("family") == "negative"
        if negative:                       # a negative row is covered by abstaining, not by a rule
            rule_ok = True
        case_ok = any(c in passed for c in r.get("cases", []))
        out.append({**r, "signals_ok": signals_ok, "unknown_signals": unknown, "rule_ok": rule_ok,
                    "case_ok": case_ok, "covered": signals_ok and rule_ok and case_ok})
    return out


def check_terms(rows: list[dict], runbooks_dir: Path) -> list[str]:
    problems = []
    for r in rows:
        for name in r.get("runbooks", []):
            found = list(runbooks_dir.glob(f"*/{name}.md"))
            if not found:
                problems.append(f"{r['id']}: runbook {name} not found under {runbooks_dir}")
                continue
            if not re.search(r.get("terms", "$^"), found[0].read_text(), re.I):
                problems.append(f"{r['id']}: {name} does not mention /{r.get('terms')}/")
    return problems


def render(results: list[dict], names: list[str], run_dir: Path | None) -> str:
    total = len(results)
    n = {k: sum(r[k] for r in results) for k in ("signals_ok", "rule_ok", "case_ok", "covered")}
    cited = {b for r in results for b in r.get("runbooks", [])}
    lines = [
        "# Diagnosis coverage",
        "",
        "Generated by `tools/coverage.py` from `tests/veracity/coverage.yaml` — do not edit.",
        "Spec: `docs/structured-diagnosis.md`. Reference catalog: prometheus-operator/runbooks",
        "@ a685d14cf512 (kubernetes/, node/) plus the families of `docs/incident-corpus.md`.",
        f"Cases graded from `{run_dir.relative_to(ROOT) if run_dir else 'no structured run'}`.",
        "",
        "A row is **covered** when its signals are extracted, its rule exists and at least one of",
        "its cases passes. These cases were written before the rules and read while writing them:",
        "a covered row is implemented, not validated.",
        "",
        "| | Rows |", "|---|---|",
        f"| Causes in the catalog | {total} |",
        f"| Signals extracted | {n['signals_ok']} |",
        f"| Rule implemented | {n['rule_ok']} |",
        f"| A case passes | {n['case_ok']} |",
        f"| **Covered** | **{n['covered']} / {total}** |",
        f"| Runbooks cited by a row | {len(cited)} / {len(names)} |",
        "",
        "| Cause | Family | Signals | Rule | Cases | Live |",
        "|---|---|---|---|---|---|",
    ]
    mark = {True: "✅", False: "—"}
    for r in results:
        sig = mark[r["signals_ok"]] + (f" (missing: {', '.join(r['unknown_signals'])})" if r["unknown_signals"] else "")
        rule = r.get("rule") or ("abstain" if r.get("family") == "negative" else "—")
        cases = ", ".join(r.get("cases", [])) or "—"
        lines.append(f"| {r['cause']} | {r['family']} | {sig} | {mark[r['rule_ok']]} {rule} | "
                     f"{mark[r['case_ok']]} {cases} | {r['live']} |")
    uncited = sorted(set(names) - cited)
    lines += ["", f"Runbooks not cited by any row ({len(uncited)}): " + ", ".join(uncited) + "."]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--runbooks", type=Path, help="runbook texts, to check each row's terms")
    args = ap.parse_args(argv)
    rows, names = load_rows(), runbook_names()
    unknown = sorted({b for r in rows for b in r.get("runbooks", [])} - set(names))
    if unknown:
        print(f"rows cite runbooks that do not exist: {unknown}", file=sys.stderr)
        return 1
    if args.runbooks:
        problems = check_terms(rows, args.runbooks)
        for p in problems:
            print(p, file=sys.stderr)
        if problems:
            return 1
    run_dir = latest_structured()
    REPORT.write_text(render(evaluate(rows, passing_cases(run_dir)), names, run_dir))
    print(f"wrote {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
