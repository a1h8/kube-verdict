#!/usr/bin/env python3
"""Structured alone vs LLM vs sLLM — the tables of docs/veracity-replay.md § Comparison.

Reads replay records (``<dir>/<solver>/<case>/run_<n>.json``), counts every expected run (a
missing one is a FAIL, fix plan H7) and prints three Markdown tables: per configuration, per
tier, per case. Never hand-written: re-run this tool.

    python tools/compare_solvers.py --none DIR --llm DIR --sllm DIR [--out FILE]
"""
from __future__ import annotations

import argparse
import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from tools.veracity_replay import TIERS, native_cases, tier_of  # noqa: E402

RUNS = {"none": 1, "LLM": 3, "sLLM": 3}
SOLVER_DIR = {"none": "structured", "LLM": "llm", "sLLM": "llm"}


def load(root: Path, name: str, cases: list[str]) -> list[dict]:
    """Every expected run of a configuration; a run without a record is MISSING."""
    out = []
    for case in cases:
        for run in range(1, RUNS[name] + 1):
            path = root / SOLVER_DIR[name] / case / f"run_{run}.json"
            if path.exists():
                rec = json.loads(path.read_text())
            else:
                expect = json.loads((ROOT / "tests/integration/cases" / case / "expect.json").read_text())
                rec = {"case": case, "run": run, "tier": tier_of(case, expect), "veracity": "MISSING"}
            out.append(rec)
    return out


def _pct(n: int, d: int) -> str:
    return f"{100 * n / d:.0f} % ({n}/{d})" if d else "—"


def _median(values: list[float]) -> str:
    values = [v for v in values if v is not None]
    return f"{statistics.median(values):.0f}" if values else "—"


def row(name: str, recs: list[dict]) -> list[str]:
    llm = name != "none"
    diagnosed = [r for r in recs if r.get("outcome", "cause") == "cause" and r["veracity"] != "MISSING"]
    proposed = [r for r in diagnosed if r.get("remediation")]
    tokens = [c.get("prompt_tokens_read") for r in recs for c in r.get("llm_calls") or []]
    return [
        name,
        _pct(sum(r["veracity"] == "PASS" for r in recs), len(recs)),
        _pct(sum(r.get("explanation_veracity") == "PASS" for r in recs), len(recs)) if llm else "n.a.",
        _pct(sum(bool(r.get("llm_disagreement")) for r in diagnosed), len(diagnosed)) if llm else "n.a.",
        _pct(len(proposed), len(diagnosed)) if llm else "n.a.",
        _pct(sum(not r.get("unrecoverable") for r in proposed), len(proposed)) if llm else "n.a.",
        str(sum(r["veracity"] == "MISSING" for r in recs)),
        _median([r.get("wall_s") for r in recs]),
        _median(tokens) if llm else "n.a.",
    ]


HEADER = ["Configuration", "Report correct", "Explanation correct", "LLM disagrees",
          "Remediation proposed", "No irreversible command", "Missing", "Median wall s",
          "Median prompt tokens"]


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def render(configs: dict[str, list[dict]]) -> str:
    parts = ["# Structured alone vs LLM vs sLLM", "",
             "Generated by `tools/compare_solvers.py` — do not edit. Protocol and decision rules: "
             "`docs/veracity-replay.md` § Comparison.", "", "## Per configuration", "",
             table(HEADER, [row(n, r) for n, r in configs.items()]), "", "## Per tier", ""]
    for tier in TIERS:
        rows = [row(f"{n} · tier {tier}", [x for x in r if x["tier"] == tier]) for n, r in configs.items()]
        if any(x["tier"] == tier for r in configs.values() for x in r):
            parts += [f"### Tier {tier}", "", table(HEADER, rows), ""]
    cases = sorted({x["case"] for r in configs.values() for x in r})
    head = ["Case"] + [f"{n} report" for n in configs] + [f"{n} explanation" for n in configs if n != "none"]
    body = []
    for case in cases:
        cells = [case]
        for n, r in configs.items():
            rs = [x for x in r if x["case"] == case]
            cells.append(f"{sum(x['veracity'] == 'PASS' for x in rs)}/{len(rs)}")
        for n, r in configs.items():
            if n != "none":
                rs = [x for x in r if x["case"] == case]
                cells.append(f"{sum(x.get('explanation_veracity') == 'PASS' for x in rs)}/{len(rs)}")
        body.append(cells)
    parts += ["## Per case", "", table(head, body), ""]
    return "\n".join(parts)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--none", required=True, type=Path)
    ap.add_argument("--llm", required=True, type=Path)
    ap.add_argument("--sllm", required=True, type=Path)
    ap.add_argument("--out", type=Path)
    args = ap.parse_args(argv)
    cases = native_cases()
    text = render({"none": load(args.none, "none", cases), "LLM": load(args.llm, "LLM", cases),
                   "sLLM": load(args.sllm, "sLLM", cases)})
    if args.out:
        args.out.write_text(text)
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
